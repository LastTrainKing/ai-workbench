# Start PostgreSQL, Redis and Qdrant as local, project-scoped processes.
# Nothing is registered as a Windows service and no system configuration is
# modified: every process, data file and log lives inside this repository.
#
#   powershell -ExecutionPolicy Bypass -File scripts\infra-start.ps1
#
. "$PSScriptRoot\lib.ps1"
Initialize-Dirs

$missing = Test-VendorPresent
if ($missing.Count -gt 0) {
    Write-Err ("Missing runtime(s): " + ($missing -join ', '))
    Write-Warn2 'Run: powershell -ExecutionPolicy Bypass -File scripts\fetch-runtime.ps1'
    exit 1
}

# --------------------------------------------------------------- PostgreSQL --
function Start-Postgres {
    if (Test-PortOpen $PgPort) {
        Write-Ok "PostgreSQL already running on $PgPort"
    }
    else {
        if (-not (Test-Path (Join-Path $PgData 'PG_VERSION'))) {
            Write-Step 'Initializing PostgreSQL data directory (first run)'
            $pwfile = Join-Path $RuntimeDir '.pgpw'
            Set-Content -Path $pwfile -Value $DbPass -NoNewline -Encoding ascii
            & (Join-Path $PgHome 'bin\initdb.exe') -D $PgData -U $PgUser -A scram-sha-256 `
                --pwfile=$pwfile -E UTF8 --locale=C | Out-Null
            Remove-Item $pwfile -Force
            if ($LASTEXITCODE -ne 0) { Write-Err 'initdb failed'; exit 1 }
            Write-Ok 'PostgreSQL cluster initialized'
        }

        Write-Step "Starting PostgreSQL on port $PgPort"
        # NOTE: we launch postgres.exe directly instead of `pg_ctl start`.
        # pg_ctl on Windows keeps a handle on the inherited stdout pipe, which makes
        # non-interactive shells (CI, scripts) block until the server exits. Starting
        # the server detached and polling the port is deterministic.
        Start-Process -FilePath (Join-Path $PgHome 'bin\postgres.exe') `
            -ArgumentList @('-D', $PgData, '-p', "$PgPort", '-c', 'listen_addresses=127.0.0.1') `
            -WorkingDirectory $PgHome -WindowStyle Hidden `
            -RedirectStandardOutput (Join-Path $LogDir 'postgres.out.log') `
            -RedirectStandardError (Join-Path $LogDir 'postgres.err.log')
        if (-not (Wait-Port $PgPort 40 'PostgreSQL')) { Write-Err "See log: $PgLog"; exit 1 }
    }

    # Provisioning is idempotent and always executed so that a partially set up
    # cluster is repaired by simply re-running this script.
    Get-PgEnv
    $psql = Join-Path $PgHome 'bin\psql.exe'

    # Idempotent role + database provisioning.
    $roleExists = & $psql -U $PgUser -p $PgPort -d postgres -tAc `
        "SELECT 1 FROM pg_roles WHERE rolname='$DbUser'"
    if ($roleExists -ne '1') {
        Write-Step "Creating role $DbUser"
        # CREATEDB is required so the test suite can create its own isolated
        # database (see backend/tests/conftest.py).
        & $psql -U $PgUser -p $PgPort -d postgres -c `
            "CREATE ROLE $DbUser LOGIN CREATEDB PASSWORD '$DbPass'" | Out-Null
    } else {
        & $psql -U $PgUser -p $PgPort -d postgres -c `
            "ALTER ROLE $DbUser CREATEDB" | Out-Null
    }
    $dbExists = & $psql -U $PgUser -p $PgPort -d postgres -tAc `
        "SELECT 1 FROM pg_database WHERE datname='$DbName'"
    if ($dbExists -ne '1') {
        Write-Step "Creating database $DbName"
        & $psql -U $PgUser -p $PgPort -d postgres -c `
            "CREATE DATABASE $DbName OWNER $DbUser ENCODING 'UTF8'" | Out-Null
        & $psql -U $PgUser -p $PgPort -d $DbName -c `
            "GRANT ALL ON SCHEMA public TO $DbUser" | Out-Null
    }
    Write-Ok "PostgreSQL ready: postgresql://${DbUser}:***@127.0.0.1:$PgPort/$DbName"
}

# -------------------------------------------------------------------- Redis --
function Start-Redis {
    if (Test-PortOpen $RedisPort) { Write-Ok "Redis already running on $RedisPort"; return }

    if (-not (Test-Path $RedisConf)) {
        Write-Step 'Writing redis.conf'
        $conf = @"
# AI Workbench - project scoped Redis (generated by scripts/infra-start.ps1)
bind 127.0.0.1
protected-mode yes
port $RedisPort
timeout 0
tcp-keepalive 300
databases 16
daemonize no
loglevel notice
logfile "$($RedisLog -replace '\\','/')"
dir "$($RedisDir -replace '\\','/')"
# Cache-only usage: persistence disabled on purpose (see docs/architecture.md).
save ""
appendonly no
maxmemory 256mb
maxmemory-policy allkeys-lru
"@
        Set-Content -Path $RedisConf -Value $conf -Encoding ascii
    }

    Write-Step "Starting Redis on port $RedisPort"
    Start-Process -FilePath (Join-Path $RedisHome 'redis-server.exe') `
        -ArgumentList @($RedisConf) -WorkingDirectory $RedisDir `
        -WindowStyle Hidden -RedirectStandardOutput (Join-Path $LogDir 'redis.out.log') `
        -RedirectStandardError (Join-Path $LogDir 'redis.err.log')
    if (-not (Wait-Port $RedisPort 20 'Redis')) { Write-Err "See log: $RedisLog"; exit 1 }
    Write-Ok "Redis ready: redis://127.0.0.1:$RedisPort/0"
}

# ------------------------------------------------------------------- Qdrant --
function Start-Qdrant {
    if (Test-PortOpen $QdrantPort) { Write-Ok "Qdrant already running on $QdrantPort"; return }

    $cfgDir = Join-Path $QdrantDir 'config'
    if (-not (Test-Path $cfgDir)) { New-Item -ItemType Directory -Path $cfgDir -Force | Out-Null }
    $cfg = Join-Path $cfgDir 'config.yaml'
    if (-not (Test-Path $cfg)) {
        Write-Step 'Writing Qdrant config.yaml'
        $yaml = @"
log_level: INFO
telemetry_disabled: true
storage:
  storage_path: ./storage
  snapshots_path: ./snapshots
  on_disk_payload: true
service:
  host: 127.0.0.1
  http_port: $QdrantPort
  grpc_port: 6334
  enable_cors: true
  max_request_size_mb: 64
"@
        Set-Content -Path $cfg -Value $yaml -Encoding ascii
    }

    Write-Step "Starting Qdrant on port $QdrantPort"
    Start-Process -FilePath (Join-Path $QdrantHome 'qdrant.exe') `
        -WorkingDirectory $QdrantDir -WindowStyle Hidden `
        -RedirectStandardOutput (Join-Path $LogDir 'qdrant.out.log') `
        -RedirectStandardError (Join-Path $LogDir 'qdrant.err.log')
    if (-not (Wait-Port $QdrantPort 40 'Qdrant')) { Write-Err "See log: $QdrantLog"; exit 1 }
    Write-Ok "Qdrant ready: http://127.0.0.1:$QdrantPort"
}

Start-Postgres
Start-Redis
Start-Qdrant

Write-Host ''
Write-Ok 'Infrastructure is up.'
Write-Host '  PostgreSQL  127.0.0.1:5432   db=aiworkbench'
Write-Host '  Redis       127.0.0.1:6379'
Write-Host '  Qdrant      http://127.0.0.1:6333/dashboard'
