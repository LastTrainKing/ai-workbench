"""Release-freeze regression tests — first-run production environment.

The confirmed defect: the installer copied ``.env.example`` to ``.env``. That template
selects ``APP_ENV=dev``, sets ``DEBUG=true`` and carries a placeholder ``SECRET_KEY`` —
and under that configuration the backend seeds ``demo / demo1234``. A fresh install came
up in development mode, with a known account, on a machine where this product reads the
user's files, runs commands and reaches the network.

The file is now generated by ``app.cli init-env``: ``APP_ENV=prod``, ``DEBUG=false``, and
a per-install random key. It runs on every launch and writes only when the file is
absent, because rotating the key on every start would sign the user out of their own
machine.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from app.core.config import DEFAULT_SECRET_KEY, Settings
from app.core.production_env import (
    ensure_production_env,
    env_problems,
    generate_secret_key,
    render_production_env,
)

REPO_ROOT = Path(__file__).resolve().parents[3]


def test_fresh_install_gets_a_production_file(tmp_path: Path) -> None:
    written = ensure_production_env(tmp_path)
    assert written is not None

    text = written.read_text(encoding="utf-8")
    assert "APP_ENV=prod" in text
    assert "DEBUG=false" in text
    assert "APP_ENV=dev" not in text
    assert "DEBUG=true" not in text
    assert "demo" not in text.lower()


def test_generated_key_satisfies_the_production_validator(tmp_path: Path) -> None:
    """The file it writes must actually let the app start in prod."""
    ensure_production_env(tmp_path)
    key = ""
    for line in (tmp_path / ".env").read_text(encoding="utf-8").splitlines():
        if line.startswith("SECRET_KEY="):
            key = line.split("=", 1)[1].strip()

    assert key and key != DEFAULT_SECRET_KEY
    assert len(key) >= 32
    # Does not raise: that is the assertion.
    Settings(_env_file=None, app_env="prod", debug=False, secret_key=key)


def test_each_install_gets_a_different_key(tmp_path: Path) -> None:
    first = tmp_path / "a"
    second = tmp_path / "b"
    ensure_production_env(first)
    ensure_production_env(second)
    assert (first / ".env").read_text(encoding="utf-8") != (
        second / ".env"
    ).read_text(encoding="utf-8")


def test_an_existing_file_is_never_touched(tmp_path: Path) -> None:
    """Upgrade and repair must not rotate the key."""
    env_path = tmp_path / ".env"
    original = "APP_ENV=prod\nDEBUG=false\nSECRET_KEY=" + "k" * 40 + "\n"
    env_path.write_text(original, encoding="utf-8")

    for _ in range(3):
        assert ensure_production_env(tmp_path) is None
    assert env_path.read_text(encoding="utf-8") == original


def test_render_refuses_to_emit_development_markers() -> None:
    text = render_production_env(generate_secret_key())
    for forbidden in ("APP_ENV=dev", "DEBUG=true", "change-me"):
        assert forbidden not in text


def test_env_problems_flags_every_unsafe_shape(tmp_path: Path) -> None:
    env_path = tmp_path / ".env"

    env_path.write_text("APP_ENV=dev\nDEBUG=true\nSECRET_KEY=" + "x" * 40, encoding="utf-8")
    problems = env_problems(env_path)
    assert "APP_ENV=dev" in problems and "DEBUG=true" in problems

    env_path.write_text("APP_ENV=prod\nSECRET_KEY=change-me-to-a-random-32-character-string", encoding="utf-8")
    assert any("placeholder" in p for p in env_problems(env_path))

    env_path.write_text("APP_ENV=prod\nSECRET_KEY=short\n", encoding="utf-8")
    assert any("32 is the minimum" in p for p in env_problems(env_path))

    env_path.write_text("APP_ENV=prod\nSECRET_KEY=\n", encoding="utf-8")
    assert "SECRET_KEY is empty" in env_problems(env_path)


def test_env_problems_accepts_a_generated_file(tmp_path: Path) -> None:
    ensure_production_env(tmp_path)
    assert env_problems(tmp_path / ".env") == []


def test_missing_file_is_reported_not_crashed(tmp_path: Path) -> None:
    assert env_problems(tmp_path / ".env") == ["no .env file"]


